#!/usr/bin/env bash
# Automatic part of the release test (D28, D32): the cases that need no
# person. Each prints OK or FALLO; the manual cases are in
# docs/prueba-v0.3.0.md.
#
# Run it ONLY on a test VM with Docker installed by CaratCore: it deletes
# Uptime Kuma and its data before starting. Use a non-root user with sudo,
# like a real user:
#
#   ./vm-test.sh ./caratcore-linux-amd64
set -u

BIN=${1:-}
if [ -z "$BIN" ] || [ ! -x "$BIN" ]; then
	echo "usage: $0 <path to the caratcore binary>" >&2
	exit 2
fi
if [ "$(id -u)" -eq 0 ]; then
	echo "run it as a normal user with sudo, as a real user would" >&2
	exit 2
fi

ID=uptime-kuma
DIR=/opt/caratcore/$ID
PORT=3001

echo "This deletes $DIR, its copies and the Uptime Kuma container."
printf "Run it only on a test VM. Type vm to continue: "
read -r answer
[ "$answer" = vm ] || { echo "Cancelled."; exit 1; }
sudo -v || exit 1
if ! docker compose version >/dev/null 2>&1; then
	echo "Docker Compose is missing: run '$BIN install docker' first" >&2
	exit 1
fi

pass=0
fail=0
ok() { echo "OK    $1"; pass=$((pass + 1)); }
ko() {
	echo "FALLO $1"
	[ -n "${2:-}" ] && printf '%s\n' "$2" | tail -n 15 | sed 's/^/      | /'
	fail=$((fail + 1))
}
# check NAME OUTPUT COMMAND...: OK when COMMAND succeeds; on FALLO, shows
# the end of OUTPUT.
check() {
	local name=$1 out=$2
	shift 2
	if "$@"; then ok "$name"; else ko "$name" "$out"; fi
}
has() { grep -qF -- "$2" <<<"$1"; }
# wait_http PORT: waits up to 90 s for an HTTP answer 2xx or 3xx. An open port
# is not enough: Docker opens it before the application is ready.
wait_http() {
	for _ in $(seq 1 90); do
		timeout 3 bash -c "exec 3<>/dev/tcp/127.0.0.1/$1 && printf 'GET / HTTP/1.0\r\n\r\n' >&3 && head -n 1 <&3" 2>/dev/null |
			grep -qE '^HTTP/1.[01] [23]' && return 0
		sleep 1
	done
	return 1
}
state_hash() { sed -n 's/.*"compose_sha256": "\([0-9a-f]*\)".*/\1/p' "$DIR/caratcore.json"; }
file_hash() { sha256sum "$DIR/compose.yaml" | cut -d' ' -f1; }
# same_hash: caratcore.json matches compose.yaml (and neither is missing).
same_hash() {
	local a b
	a=$(state_hash)
	b=$(file_hash)
	[ -n "$a" ] && [ "$a" = "$b" ]
}

echo
echo "== Clean start"
[ -f "$DIR/compose.yaml" ] && sudo docker compose --file "$DIR/compose.yaml" down >/dev/null 2>&1
sudo rm -rf -- "$DIR" "$DIR".bak-*

out=$("$BIN" version 2>&1)
check "version: $out" "$out" has "$out" "caratcore "

out=$("$BIN" list 2>&1)
check "list: $ID not installed" "$out" grep -qE "^$ID +not installed" <<<"$out"

echo
echo "== Install (D32: state file)"
out=$("$BIN" install $ID --dry-run 2>&1)
check "install --dry-run writes caratcore.json" "$out" has "$out" "Write $DIR/caratcore.json"

out=$(echo yes | "$BIN" install $ID 2>&1)
check "install $ID" "$out" has "$out" "all 5 step(s) completed"
check "caratcore.json exists" "$out" test -f "$DIR/caratcore.json"
check "caratcore.json hash = sha256sum compose.yaml" "$(cat "$DIR/caratcore.json" 2>&1)" same_hash
check "web answers on $PORT" "" wait_http $PORT

out=$("$BIN" list 2>&1)
check "list: up to date" "$out" grep -qE "^$ID +up to date" <<<"$out"

out=$(echo yes | "$BIN" install $ID 2>&1)
check "install again (repeatable)" "$out" has "$out" "all 5 step(s) completed"

out=$("$BIN" update $ID --dry-run 2>&1)
check "update when up to date: 1 step (start)" "$out" has "$out" "1 step(s)"

echo
echo "== Update from an older version (D33)"
# Pretend an older CaratCore wrote compose.yaml: change its first comment
# and record the new hash, as that version would have.
sudo sed -i 's/^# Generated by CaratCore\./# Generated by an older CaratCore./' "$DIR/compose.yaml"
image=$(sed -n 's/^    image: //p' "$DIR/compose.yaml")
printf '{\n  "caratcore_version": "v0.2.0",\n  "image": "%s",\n  "compose_sha256": "%s"\n}\n' "$image" "$(file_hash)" |
	sudo tee "$DIR/caratcore.json" >/dev/null

out=$("$BIN" list 2>&1)
check "list: update available" "$out" grep -qE "^$ID +update available" <<<"$out"

out=$(echo yes | "$BIN" install $ID 2>&1)
check "install refuses and points to update" "$out" has "$out" "caratcore update $ID"

out=$("$BIN" update $ID --dry-run 2>&1)
check "update --dry-run: 6 steps" "$out" has "$out" "6 step(s)"

out=$(echo yes | "$BIN" update $ID 2>&1)
check "update $ID" "$out" has "$out" "all 6 step(s) completed"
backup=$(ls -d "$DIR".bak-* 2>/dev/null | head -n 1)
check "copy made: ${backup:-none}" "$out" test -n "$backup"
check "copy has compose.yaml and data" "$(sudo ls -la "$backup" 2>&1)" sudo test -f "$backup/compose.yaml" -a -d "$backup/data"
check "next steps explain how to go back" "$out" has "$out" "sudo mv $backup $DIR"
check "caratcore.json updated" "$(cat "$DIR/caratcore.json" 2>&1)" same_hash
check "web answers on $PORT after update" "" wait_http $PORT

out=$("$BIN" list 2>&1)
check "list: up to date, copy listed" "$out" grep -qE "^$ID +up to date" <<<"$out"
check "list shows the copy" "$out" has "$out" "$backup"

out=$("$BIN" update $ID --dry-run 2>&1)
check "update again: 1 step" "$out" has "$out" "1 step(s)"

echo
echo "== Edited compose.yaml (D23, D32)"
echo "# my change" | sudo tee -a "$DIR/compose.yaml" >/dev/null

out=$("$BIN" list 2>&1)
check "list: edited" "$out" grep -qE "^$ID +edited" <<<"$out"
out=$("$BIN" update $ID --dry-run 2>&1)
check "update refuses an edited file" "$out" has "$out" "would overwrite your changes"
out=$(printf '%s\n' $ID | "$BIN" uninstall $ID --purge 2>&1)
check "uninstall --purge refuses an edited file" "$out" has "$out" "without --purge"
check "folder still there" "" test -f "$DIR/compose.yaml"

echo
echo "== Uninstall --purge (D30, D33)"
sudo sed -i '/^# my change$/d' "$DIR/compose.yaml"
out=$(printf '%s\n' $ID | "$BIN" uninstall $ID --purge 2>&1)
check "uninstall --purge" "$out" has "$out" "all 2 step(s) completed"
check "folder deleted" "" test ! -e "$DIR"
check "copy kept" "" test -d "$backup"
check "next steps name the copy" "$out" has "$out" "$backup"

out=$("$BIN" list 2>&1)
check "list: not installed, copy listed" "$out" grep -qE "^$ID +not installed" <<<"$out"

sudo rm -rf -- "$DIR".bak-*

echo
echo "Result: $pass OK, $fail FALLO"
[ "$fail" -eq 0 ]
